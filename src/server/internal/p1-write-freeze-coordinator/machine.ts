export function transition(state: CoordinatorState, event: CoordinatorEvent): TransitionResult {
  const next = EDGES[state][event];
  if (next === undefined) return { ok: false, code: "INVALID_TRANSITION" };
  return { ok: true, state: next };
}

export function isCoordinatorState(value: string): value is CoordinatorState {
  return (COORDINATOR_STATES as readonly string[]).includes(value);
}

export function isCoordinatorEvent(value: string): value is CoordinatorEvent {
  return (COORDINATOR_EVENTS as readonly string[]).includes(value);
}
